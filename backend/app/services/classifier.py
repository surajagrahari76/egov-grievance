def _score_keyword(combined: str, keyword: str) -> int:
    """Count matches for a keyword using letter boundaries for ASCII and substring for Devanagari."""
    if keyword.isascii():
        pattern = rf"(?<![a-z]){re.escape(keyword)}(?![a-z])"
        return len(re.findall(pattern, combined))
    return combined.count(keyword)


def classify_category(title: str, text: str) -> str | None:
    """Classify a grievance into a seeded department code using EN/HI/Hinglish keywords."""
    combined = f"{title or ''} {text or ''}".lower().strip()
    if not combined:
        return None

    best_code: str | None = None
    best_score = 0

    for dept_code, keywords in DEPARTMENT_KEYWORDS.items():
        score = sum(_score_keyword(combined, kw) for kw in keywords)
        if score > best_score:
            best_score = score
            best_code = dept_code

    return best_code if best_score > 0 else None
